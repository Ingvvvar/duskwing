/**
 * Детерминированный источник случайности.
 *
 * `Math.random` внутри `src/game/**` запрещён и проверяется тестом
 * `tests/game-boundary.test.ts`: раскладка уровня должна воспроизводиться по
 * сиду — и в тестах, и чтобы одна и та же попытка повторялась один в один.
 */

/** Возвращает число в [0, 1). */
export type Rng = () => number;

/**
 * mulberry32: 32-битный PRNG на одном слове состояния. Выбран за то, что
 * укладывается в семь строк и не требует внешних зависимостей; статистическое
 * качество для разброса просветов избыточно.
 */
export function mulberry32(seed: number): Rng {
  let state = seed >>> 0;

  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
