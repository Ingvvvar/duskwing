import { WORLD_WIDTH } from '../game/constants';

/**
 * Ширина зоны проявления препятствия у правой кромки, px мира.
 *
 * Раньше кромку закрывала полоса дымки поверх игрового слоя. Она решала ту же
 * задачу — препятствие проступает из глубины, а не выезжает из-под ножа
 * маски, — но делала это чужими пикселями: над трубой лежал ещё один спрайт.
 * Проявлять само препятствие честнее: игрок видит ровно то, что его убьёт, без
 * посредника.
 */
export const REVEAL_WIDTH = 40;

/**
 * Непрозрачность препятствия по его мировому иксу.
 *
 * Ноль в момент появления за правым краем, единица через `REVEAL_WIDTH`
 * пройденных пикселей, дальше единица всегда.
 *
 * Зона намеренно узкая. На самой быстрой скорости, которую даёт игра (190 px/s
 * — пятый уровень на своей цели и бесконечный режим на сотне труб), препятствие
 * проходит её за 211 мс и дальше стоит полностью непрозрачным ещё 1137 мс до
 * икса птицы. Допуск на реакцию — около 150 мс, то есть запас 7.6-кратный.
 * На первом уровне это 333 мс и 1800 мс.
 */
export function obstacleReveal(x: number): number {
  const travelled = WORLD_WIDTH - x;

  if (travelled <= 0) {
    return 0;
  }

  return Math.min(1, travelled / REVEAL_WIDTH);
}
